#!/usr/bin/env python3
"""text_hygiene.py — deterministic post-pass for delivered prose.

Fixes three classes of residual defects that the generator/polish layers leave
behind (found in client QA, never generated by this script):

  1. sentence-initial lowercase  ("and the best defence is…" → "And …")
  2. common contractions         (doesn't → does not, it's → it is, …)
  3. downcased proper nouns      (garena → Garena, free fire → Free Fire, …)

Rules are conservative: reference lines (URLs / DOIs) are never touched, and
the script reports every change so a human can review the diff.

Usage:
  python text_hygiene.py in.docx out.docx [--json report.json] [--dry-run]
"""
import argparse
import json
import re
import sys

CONTRACTIONS = {
    r"\bit's\b": "it is",
    r"\bthat's\b": "that is",
    r"\bdoesn't\b": "does not",
    r"\bdon't\b": "do not",
    r"\bdidn't\b": "did not",
    r"\bisn't\b": "is not",
    r"\bcan't\b": "cannot",
    r"\bwon't\b": "will not",
    r"\bthey're\b": "they are",
    r"\bwe're\b": "we are",
    r"\bit'll\b": "it will",
    r"\bhe's\b": "he is",
    r"\bshe's\b": "she is",
    r"\bwho's\b": "who is",
    r"\bthere's\b": "there is",
}
PROPER = {
    "garena": "Garena",
    "free fire": "Free Fire",
    "ronaldo": "Ronaldo",
    "cristiano": "Cristiano",
    "youtube": "YouTube",
    "malaysia": "Malaysia",
    "chrono": "Chrono",
}
REF_LINE = re.compile(r"^(https?://|doi:|10\.\d{4,}/\S)", re.I)
SENT_END = re.compile(r"([.!?][\"')\]]?\s+)([a-z])")


def _is_ref_block(paragraphs):
    """Indices from the References heading onward."""
    out = set()
    inrefs = False
    for i, p in enumerate(paragraphs):
        if re.match(r"^\s*(references?|works cited|bibliography)\s*:?\s*$", p, re.I):
            inrefs = True
            out.add(i)
            continue
        if inrefs:
            out.add(i)
    return out


def clean_paragraph(text, allow_proper=True):
    """Return (new_text, ops)."""
    ops = []
    if REF_LINE.match(text.strip()):
        return text, ops
    orig = text
    for pat, rep in CONTRACTIONS.items():
        new = re.sub(pat, rep, text, flags=re.I)
        if new != text:
            ops.append({"type": "contraction", "pattern": pat})
            text = new
    # capitalise after sentence boundaries
    new = SENT_END.sub(lambda m: m.group(1) + m.group(2).upper(), text)
    if new != text:
        ops.append({"type": "sentence-capital", "count": len(SENT_END.findall(text))})
        text = new
    # capitalise sentence starts at paragraph start
    stripped = text.lstrip()
    if stripped and stripped[0].islower():
        text = text[: len(text) - len(stripped)] + stripped[0].upper() + stripped[1:]
        ops.append({"type": "paragraph-capital"})
    if allow_proper:
        for low, proper in PROPER.items():
            pat = re.compile(r"\b" + re.escape(low) + r"\b", re.I)
            hits = [m.group(0) for m in pat.finditer(text) if m.group(0) != proper]
            if hits:
                text = pat.sub(proper, text)
                ops.append({"type": "proper-noun", "word": proper, "fixed": len(hits)})
    return text, ops


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("inp")
    ap.add_argument("outp")
    ap.add_argument("--json")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    from docx import Document
    doc = Document(a.inp)
    paras = [p.text or "" for p in doc.paragraphs]
    refs = _is_ref_block(paras)
    report, changed = [], 0
    for i, p in enumerate(doc.paragraphs):
        text = p.text or ""
        if not text.strip() or i in refs:
            continue
        new, ops = clean_paragraph(text)
        if ops and new != text:
            changed += 1
            report.append({"para": i, "ops": ops, "before": text[:90], "after": new[:90]})
            runs = p.runs
            if runs:
                runs[0].text = new
                for r in runs[1:]:
                    r.text = ""
    if not a.dry_run:
        doc.save(a.outp)
    summary = {"paragraphs_changed": changed, "edits": report}
    print(json.dumps(summary, ensure_ascii=False, indent=1))
    if a.json:
        json.dump(summary, open(a.json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
